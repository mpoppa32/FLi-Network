// Corsair main module — entry orchestrator
//
// Loads sibling modules under js/corsair/. Each imported module
// publishes to window.Corsair.<name> and (where back-compat is required)
// also exposes select helpers as bare window globals.

import './util.js';
import './pipeline.js';
import './state.js';
import './posture.js';
import './inspector.js';
import './cop.js';
import './rhythm.js';
import './brief.js';
import './theater.js';
import './table.js';

(function init(){
  if (typeof window === 'undefined') return;
  window.Corsair = window.Corsair || {};
  window.Corsair.buildTag    = 'P13.118';
  window.Corsair.buildBlurb  = 'Audit Finding 3.3 batch 3 — fixed 11 more XSS innerHTML callsites in the daily BD workflow surfaces: opp name in selection panel, opp option in opportunity-picker <select> (also escaped o.id which goes into the value attribute), meeting title in tooltip + meeting-list rows (3 callsites in the meeting search/recent surfaces), meeting title in archive sidebar, body panels showing m.meta.title + o.name (3 callsites in re-engage / batch panels), Inspector linked-opp tag list, Inspector meeting-history card title, Inspector timeline meeting title. Combined with P13.117 (9 callsites), 20 of the audit\'s named ~25 XSS surfaces are now escaped. Daily-workflow surfaces (TODAY → Pipeline → Inspector → Brief → Network → Timeline) are fully covered. Critical Findings closed total: 13 (3.3 batched, getting close to full coverage).';
  window.Corsair.modules     = window.Corsair.modules || {};

  if (typeof document !== 'undefined') {
    // Single source of truth — both surfaces read the same tag.
    var auth = document.getElementById('auth-build-tag');
    if (auth) auth.textContent = window.Corsair.buildTag;
    var hud = document.getElementById('de3d-build');
    if (hud)  hud.textContent  = window.Corsair.buildTag;

    // P11.10 layout fix: posture-view was inserted at body level after
    // the other top-level views, but the other views live inside the
    // #main-app flex container. flex:1 on posture-view therefore
    // resolved against <body> (not flex), giving it only ~389px of
    // height. Reparent it into #main-app so its flex:1 fills the
    // visible content area like the other views.
    var mainApp     = document.getElementById('main-app');
    var postureView = document.getElementById('posture-view');
    if (mainApp && postureView && postureView.parentNode !== mainApp) {
      mainApp.appendChild(postureView);
    }
  }

  console.log(
    '%c[Corsair] modules loaded · ' + window.Corsair.buildTag + ' · ' +
    window.Corsair.buildBlurb + ' · ' + new Date().toISOString(),
    'color:#d4823a;font-weight:bold'
  );
})();
